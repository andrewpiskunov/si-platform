import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base = process.env.BASE_URL || 'http://localhost:5173';
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined });
try {
  const page = await browser.newPage();
  page.setDefaultTimeout(10000);
  page.setDefaultNavigationTimeout(10000);
  await page.goto(base + '/');
  await page.getByRole('heading', { name: 'Своя игра. В браузере.' }).waitFor();
  assert.equal(await page.getByRole('textbox', { name: 'Поиск пакетов' }).count(), 0, 'Home must not contain catalogue filters');
  await page.getByRole('navigation', { name: 'Основная навигация' }).getByRole('link', { name: 'Каталог', exact: true }).click();
  await page.waitForURL('**/packs');
  await page.getByRole('heading', { name: 'Каталог пакетов', exact: true }).waitFor();
  assert.equal(await page.locator('.landing').count(), 0);
  await page.waitForLoadState('networkidle');
  await page.getByRole('textbox', { name: 'Поиск пакетов' }).fill('нет такого пакета');
  await page.getByRole('button', { name: 'Найти', exact: true }).click();
  await page.waitForURL(url => url.pathname === '/packs' && url.searchParams.get('q') === 'нет такого пакета');
  await page.getByRole('link', { name: 'Сбросить фильтры', exact: true }).click();
  await page.waitForURL('**/packs');
  await page.goto(base + '/rooms');
  await page.getByRole('button', { name: 'Создать комнату', exact: true }).first().click();
  await page.getByRole('dialog', { name: 'Создать комнату' }).waitFor();
  await page.keyboard.press('Escape');
  const room = 'a'.repeat(32);
  await page.goto(base + '/?q=старый&room=' + room);
  await page.waitForLoadState('networkidle');
  assert.equal(new URL(page.url()).pathname, '/packs', 'Legacy search redirects to catalogue');
  assert.equal(new URL(page.url()).searchParams.get('room'), room);
  await page.getByRole('textbox', { name: 'Поиск пакетов' }).fill('новый');
  await page.getByRole('button', { name: 'Найти', exact: true }).click();
  await page.waitForURL(url => url.pathname === '/packs' && url.searchParams.get('q') === 'новый');
  assert.equal(new URL(page.url()).searchParams.get('room'), room);
  await page.goto(base + '/packs/' + 'b'.repeat(32));
  await page.getByRole('link', { name: 'В каталог', exact: true }).click();
  await page.waitForURL('**/packs');
  await page.getByRole('link', { name: 'Своя игра — главная', exact: true }).click();
  await page.waitForURL(base + '/');
  assert.equal(await page.locator('nav[aria-label="Основная навигация"] a.active').count(), 0);
  console.log('PASS: separate home/catalogue, room link, search/reset, legacy URLs, room context and return links');
} finally { await browser.close(); }
