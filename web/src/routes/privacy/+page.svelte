  <h1>Хранение и удаление данных</h1>
  <p>
    Здесь описаны правила хранения в сервисе. Срок означает, что данные становятся доступны для
    фоновой очистки. Проверка выполняется раз в минуту небольшими порциями; при сбое базы или
    хранилища удаление повторяется. Физическое удаление не обещается в точную секунду.
  </p>
  <h2>Материалы и загрузки</h2>
  <ul>
    <li>
      Удалённые пакеты и оформления очищаются через 30 дней после удаления. При удалении аккаунта
      отсчёт для его материалов начинается с удаления аккаунта.
    </li>
    <li>
      Готовые и неудачные загрузки очищаются через 30 дней после последнего изменения статуса.
      Незавершённые загрузки истекают через 24 часа. Временные входные файлы также очищаются.
    </li>
    <li>
      Прикреплённые файлы сохраняются в версиях материалов. Отдельный подготовленный результат
      загрузки не является бессрочным хранилищем: сохраните его в материал до окончания срока.
    </li>
  </ul>
  <p>
    Версия, используемая живой комнатой, сохраняется до удаления последней такой привязки.
    Подготовка выгрузки данных также откладывает очистку записей и файлов владельца. Готовый ZIP уже
    не зависит от исходных файлов.
  </p>
  <p>
    Один файл может использоваться несколькими материалами и владельцами. Его байты удаляются только
    после исчезновения последней ссылки: удаление вашего аккаунта не удаляет чужую копию.
  </p>
  <h2>Подключённые авторские инструменты</h2>
  <p>
    Для разрешённого импорта каталога сохраняются исходный идентификатор, контрольная сумма,
    ссылка, лицензия, атрибуция и указанное оператором основание разрешения. Записи входят в
    выгрузку владельца и сохраняются после удаления пакета для защиты от повторного создания.
    Через 30 дней после удаления аккаунта они очищаются; активная выгрузка откладывает очистку.
    Основание разрешения не публикуется в каталоге.
  </p>
  <p>
    Для изменений через MCP сохраняются ключ повтора, вид операции, идентификатор пакета и версия
    результата. Эти записи предотвращают повторное создание удалённого пакета и входят в выгрузку
    аккаунта. После удаления аккаунта они очищаются через 30 дней; активная выгрузка откладывает
    очистку. Тексты запросов в этих служебных записях не сохраняются.
  </p>
  <h2>ИИ-помощник</h2>
  <p>
    При расчёте оценки запрос и аудитория передаются настроенному провайдеру; локальный тестовый
    режим не отправляет их в сеть. Задания, предложения и расход входят в выгрузку данных аккаунта.
    Завершённые задания очищаются через 90 дней, либо через 30 дней после удаления аккаунта.
    Истёкшие оценки удаляются. Месячные суммы сохраняются независимо от истории заданий:
    прошлые месяцы очищаются через 90 дней, текущий месяц сохраняется для контроля лимита.
    Неопределённый результат может удерживать резерв до конца месяца; генерация автоматически
    не повторяется. Правила хранения у внешнего провайдера определяются его условиями.
  </p>
  <h2>Аккаунт и журнал действий</h2>
  <p>
    После удаления аккаунта доступ к нему и его публикациям закрывается, имя и учётные данные
    становятся недоступны сразу. Перед удалением скачайте свои данные в настройках аккаунта.
  </p>
  <ul>
    <li>
      Журнал действий действующего аккаунта хранится до 90 дней; журнал удалённого аккаунта доступен
      для очистки через 30 дней после удаления аккаунта.
    </li>
    <li>
      Истёкшие или отозванные учётные данные очищаются через 30 дней после прекращения действия,
      когда на них больше не ссылаются загрузки.
    </li>
    <li>
      Через 30 дней после удаления аккаунта авторские тексты его жалоб и решений модерации
      заменяются отметкой об удалении. Для чужих живых материалов сохраняются статус и время
      решения.
    </li>
  </ul>
  <p>
    История модерации и жалоб на материал удаляется вместе с самим материалом. Минимальный
    технический ID удалённого аккаунта может остаться для связей с чужими решениями; исходные имя,
    пароль и авторские тексты в такой записи не сохраняются. Гостевые игроки не связываются с
    аккаунтом по совпадению имени.
  </p>
  <h2>Игровые комнаты</h2>
  <ul>
    <li>Лобби: 7 дней без принятых действий участников.</li>
    <li>Незавершённая игра: 30 дней без принятых действий участников.</li>
    <li>Завершённая игра: 30 дней после завершения.</li>
    <li>Любая комната: общий предел 90 дней с создания.</li>
  </ul>
  <p>
    Применяется ближайший срок. Присоединение участников и принятые действия продлевают срок
    неактивности, но не предел 90 дней. Переподключение, чтение табло, проверка соединения и
    автоматические таймеры срок не продлевают. Текущий срок виден участникам в комнате, в том числе
    гостям.
  </p>
  <p>
    При очистке комнаты удаляются её сессии, приглашение, журнал игры, результаты, места участников
    и привязки пакета и оформления. Старое приглашение перестаёт работать; подключённые клиенты
    прекращают повторное подключение и отправку прежних команд.
  </p>
  <h2>Границы этих правил</h2>
  <p>
    Очистка относится к зарегистрированным объектам рабочего хранилища сервиса. Эти сроки не
    описывают удаление из резервных копий: для них и для восстановления данных нужна отдельная
    эксплуатационная процедура. Здесь не даётся заключение о соответствии законодательству страны
    размещения.
  </p>
